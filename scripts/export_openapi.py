"""Write the OpenAPI document and the endpoint index to docs/api/.

    uv run python scripts/export_openapi.py            # rebuild docs/api/openapi.json and docs/api/endpoints.md
    uv run python scripts/export_openapi.py --record   # first rerun the test suite to refresh response examples
    uv run python scripts/export_openapi.py --check    # exit 1 if the committed files are stale

No database or real keys are needed: the app is built with a throwaway signing key so every router mounts.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

DOCS = ROOT / "docs" / "api"
SPEC_PATH = DOCS / "openapi.json"
INDEX_PATH = DOCS / "endpoints.md"


def build_spec() -> dict:
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from cryptography.hazmat.primitives.serialization import Encoding, NoEncryption, PrivateFormat, PublicFormat

    from src import openapi
    from src.main import create_app

    key = Ed25519PrivateKey.generate()
    app = create_app(
        database_url="postgresql+psycopg://docs@127.0.0.1:1/docs",
        jwt_private_key=key.private_bytes(Encoding.PEM, PrivateFormat.PKCS8, NoEncryption()).decode(),
        jwt_public_key=key.public_key().public_bytes(Encoding.PEM, PublicFormat.SubjectPublicKeyInfo).decode(),
        razorpay_key_id="rzp_docs",
    )
    spec = openapi.build(app)
    return {"openapi": spec.pop("openapi"), "info": spec.pop("info"), "servers": openapi.SERVERS, **spec}


def render_spec(spec: dict) -> str:
    return json.dumps(spec, indent=2, sort_keys=False, ensure_ascii=False) + "\n"


def role_label(roles: list[str]) -> str:
    from src.auth import policies

    names = {
        policies.ADMIN_READ_ROLES: "staff (not JUDGE)",
        policies.ADMIN_PORTAL_ROLES: "any staff",
        policies.EVENT_CONTROL_ROLES: "SUPER_ADMIN, EVENT_ADMIN",
    }
    return names.get(frozenset(roles), ", ".join(roles))


def render_index(spec: dict) -> str:
    lines = [
        "# Endpoint index",
        "",
        "Generated by `scripts/export_openapi.py` from the running code. Do not edit by hand.",
        "Full schemas and examples: [`openapi.json`](openapi.json) (open it in Swagger UI, Redoc, Postman or Insomnia),",
        "or `/docs` on a running API. The guide is [`README.md`](README.md).",
        "",
        "Auth: `public` needs nothing; otherwise send `Authorization: Bearer <access_token>` from a user holding one of",
        "the listed roles. `staff (not JUDGE)` is SUPER_ADMIN, EVENT_ADMIN, REGISTRATION_ADMIN, EVALUATION_ADMIN,",
        "SUPPORT_ADMIN and VIEWER. `PARTICIPANT` means the team leader's account.",
        "",
    ]
    by_tag: dict[str, list[tuple[str, str, dict]]] = {}
    for path, operations in spec["paths"].items():
        for method, operation in operations.items():
            by_tag.setdefault((operation.get("tags") or ["other"])[0], []).append((method.upper(), path, operation))
    descriptions = {tag["name"]: tag["description"] for tag in spec.get("tags", [])}
    order = [tag["name"] for tag in spec.get("tags", [])]
    total = sum(len(v) for v in by_tag.values())
    lines.append(f"{total} operations.")
    lines.append("")
    lines.append("| Group | Operations |")
    lines.append("|---|---|")
    for tag in sorted(by_tag, key=lambda t: (order.index(t) if t in order else len(order), t)):
        lines.append(f"| [{tag}](#{tag}) | {len(by_tag[tag])} |")
    for tag in sorted(by_tag, key=lambda t: (order.index(t) if t in order else len(order), t)):
        lines += ["", f"## {tag}", ""]
        if tag in descriptions:
            lines += [descriptions[tag], ""]
        lines += ["| Method | Path | Auth | Body | Success |", "|---|---|---|---|---|"]
        for method, path, operation in by_tag[tag]:
            roles = operation.get("x-roles")
            if not operation.get("security"):
                auth = "public"
            elif roles:
                auth = role_label(roles)
            else:
                auth = "any signed-in user"
            content = operation.get("requestBody", {}).get("content", {})
            body = next(iter(content), "") if content else ""
            ref = content.get(body, {}).get("schema", {}).get("$ref", "") if body else ""
            body = ref.rsplit("/", 1)[-1] if ref else body
            success = next((code for code in operation["responses"] if code.startswith("2")), "")
            query = [p["name"] for p in operation.get("parameters", []) if p.get("in") == "query"]
            shown = f"`{path}`" + (f" `?{'&'.join(query)}`" if query else "")
            lines.append(f"| `{method}` | {shown} | {auth} | {body} | {success} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--record", action="store_true", help="rerun the test suite to refresh src/openapi_examples.json")
    parser.add_argument("--check", action="store_true", help="fail if docs/api is out of date")
    args = parser.parse_args()

    if args.record:
        env = {**os.environ, "RECORD_OPENAPI_EXAMPLES": "1"}
        result = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], cwd=ROOT, env=env)
        if result.returncode not in (0, 1):
            return result.returncode

    spec = build_spec()
    outputs = {SPEC_PATH: render_spec(spec), INDEX_PATH: render_index(spec)}
    if args.check:
        stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run: uv run python scripts/export_openapi.py)")
        return 1 if stale else 0
    DOCS.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
